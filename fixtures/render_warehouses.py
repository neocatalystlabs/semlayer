"""Render docs/warehouses.md from the registries, the built databases and the CI gates.

Three sources, each authoritative for its own part, so nothing is typed twice:

- `fixtures/registry.yaml`          — the synthetic warehouses and what each is for
- `fixtures/external/registry.yaml` — the acquired datasets, including the licence
  verification that decides whether anything derived from them may ship
- the built `.duckdb` files          — shape (tables/columns/rows), measured not typed
- the test modules' floor constants  — the accuracy numbers CI actually enforces

Reading the floors out of the test modules rather than restating them is the
point: a doc that quotes a number nobody enforces goes stale silently, and this
one cannot disagree with the gate because it IS the gate.

Usage:
    python fixtures/render_warehouses.py            # write docs/warehouses.md
    python fixtures/render_warehouses.py --check     # exit 1 if out of date
"""

from __future__ import annotations

import ast
import pathlib
import sys

import duckdb
import yaml

OSS = pathlib.Path(__file__).resolve().parent.parent
OUT = OSS / "docs" / "warehouses.md"


def _floors(rel: str, const: str) -> dict:
    """Read a floor dict out of a test module WITHOUT importing it.

    The test modules import semlayer and duckdb at module scope, so importing
    them from a docs renderer would drag the whole engine in. The constants are
    plain literals, so the AST is enough.
    """
    tree = ast.parse((OSS / rel).read_text())
    for node in tree.body:
        if isinstance(node, ast.Assign) and any(
                getattr(t, "id", None) == const for t in node.targets):
            return ast.literal_eval(node.value)
    return {}


def _shape(name: str) -> dict | None:
    db = OSS / "fixtures" / "build" / f"{name}.duckdb"
    if not db.exists():
        return None
    con = duckdb.connect(str(db), read_only=True)
    try:
        tabs = con.execute(
            "SELECT table_schema, table_name FROM information_schema.tables "
            "WHERE table_schema NOT IN ('information_schema','pg_catalog') "
            "AND table_catalog = current_catalog()").fetchall()
        cols = con.execute(
            "SELECT count(*) FROM information_schema.columns "
            "WHERE table_schema NOT IN ('information_schema','pg_catalog')").fetchone()[0]
        rows = 0
        for sch, tn in tabs:
            try:
                rows += con.execute(f'SELECT count(*) FROM "{sch}"."{tn}"').fetchone()[0]
            except Exception:
                # A view over a table that no longer resolves is not fatal to a
                # shape count; the other tables still report.
                pass
        return {"tables": len(tabs), "schemas": len({s for s, _ in tabs}),
                "columns": cols, "rows": rows}
    finally:
        con.close()


def _gold(name: str) -> dict:
    g = OSS / "fixtures" / "golds" / f"{name}.yaml"
    if not g.exists():
        return {}
    sl = (yaml.safe_load(g.read_text()) or {}).get("semantic_layer", {})
    return {
        "fks": sum(1 for t in sl.get("tables", [])
                   for c in t.get("columns", []) if c.get("foreign_key")),
        "relationships": len(sl.get("relationships", []) or []),
        "hierarchies": len(sl.get("hierarchies", []) or []),
        "metrics": len(sl.get("metrics", []) or []),
    }


def _n(v) -> str:
    return f"{v:,}" if isinstance(v, int) else "—"


def render() -> str:
    syn = yaml.safe_load((OSS / "fixtures" / "registry.yaml").read_text())["synthetic"]
    ext_doc = yaml.safe_load((OSS / "fixtures" / "external" / "registry.yaml").read_text())
    ext = ext_doc["datasets"] if isinstance(ext_doc, dict) and "datasets" in ext_doc else ext_doc
    fk_floors = _floors("tests/test_link.py", "FK_FLOORS")
    acq_floors = _floors("tests/test_acquired_fk_floors.py", "FLOORS")

    L: list[str] = []
    L.append("<!-- GENERATED by fixtures/render_warehouses.py — do not edit by hand. -->")
    L.append("")
    L.append("# The warehouses we evaluate against")
    L.append("")
    L.append("Every number semlayer publishes comes from one of these. This page says "
             "which they are, where they came from, what they are each designed to "
             "catch, and what CI enforces on each — so a claim can be traced to a "
             "warehouse rather than taken on trust.")
    L.append("")
    L.append("Two kinds. **Synthetic** warehouses we generate: deterministic, "
             "seeded, rebuilt by `python fixtures/build.py`, with hand-authored gold "
             "covering every column — so they can be scored exactly, and we can state "
             "a business rule that no real schema would tell us. **Acquired** "
             "real-world datasets: messy in ways we would not think to invent, scored "
             "against the vendor's own declared keys, and never redistributed — we "
             "ship a fetch script, not data.")
    L.append("")

    # --- synthetic -----------------------------------------------------------
    L.append("## Synthetic (9)")
    L.append("")
    L.append("| warehouse | tables | columns | rows | gold FKs | CI floor P/R |")
    L.append("|---|--:|--:|--:|--:|---|")
    for e in syn:
        n = e["name"]
        s = _shape(n) or {}
        g = _gold(n)
        f = fk_floors.get(n)
        floor = f"{f[0]:.2f} / {f[1]:.2f}" if f else "— *(no FK gate)*"
        t = _n(s.get("tables"))
        if s.get("schemas", 1) > 1:
            t += f" *in {s['schemas']} schemas*"
        L.append(f"| `{n}` | {t} | {_n(s.get('columns'))} | {_n(s.get('rows'))} "
                 f"| {_n(g.get('fks'))} | {floor} |")
    L.append("")
    L.append("Blank floors are real gaps, not omissions: four fixtures carry gold but "
             "no CI-enforced foreign-key floor, so a regression on them would not fail "
             "the build. They are listed here so the gap is visible.")
    L.append("")
    for e in syn:
        n = e["name"]
        g = _gold(n)
        L.append(f"### `{n}`")
        L.append("")
        L.append(" ".join(e["purpose"].split()))
        L.append("")
        bits = [f"generator `{e['generator']}`"]
        if e.get("seeded"):
            bits.append("seeded, so two builds are byte-identical")
        if g:
            bits.append(f"gold asserts {g['fks']} foreign keys, "
                        f"{g['relationships']} relationships, "
                        f"{g['hierarchies']} hierarchies, {g['metrics']} metrics")
        L.append("- " + "; ".join(bits) + ".")
        if e.get("notes"):
            L.append("- " + " ".join(e["notes"].split()))
        L.append("")

    # --- acquired ------------------------------------------------------------
    pub = [d for d in ext if d.get("track") == "P"]
    internal = [d for d in ext if d.get("track") != "P"]

    L.append(f"## Acquired, published ({len(pub)})")
    L.append("")
    L.append("Real datasets under a licence that lets us publish results and ship "
             "everything needed to reproduce them. We still distribute only the fetch "
             "script — the data stays with its owner.")
    L.append("")
    L.append("Shape below is **as recorded at acquisition**, not measured on this "
             "machine: the data is not in the repository, so CI cannot count it. "
             "Synthetic shapes above ARE measured from the built database.")
    L.append("")
    L.append("| dataset | source | pinned at | licence | tables | columns | rows | CI floor P/R |")
    L.append("|---|---|---|---|--:|--:|--:|---|")
    for d in pub:
        n = d["name"]
        # An acquired dataset can carry more than one floor: dbt_synthea is gated
        # both with and without its ETL manifest, and the gap between those two
        # rows IS the finding, so collapsing them to one number would hide it.
        keys = [k for k in acq_floors if isinstance(k, (list, tuple)) and k[0] == n]
        if keys:
            parts = []
            for k in sorted(keys, key=lambda k: bool(k[1])):
                tag = "with manifest" if k[1] else "warehouse alone"
                parts.append(f"{acq_floors[k][0]:.2f} / {acq_floors[k][1]:.2f} *({tag})*")
            floor = "<br>".join(parts)
        else:
            floor = "— *(no FK gate)*"
        ver = d.get("version") or d.get("sha256") or "—"
        L.append(f"| `{n}` | [{d.get('source', '—')}]({d.get('source', '')}) | `{ver}` "
                 f"| {d.get('licence', '—')} | {_n(d.get('tables'))} "
                 f"| {_n(d.get('columns'))} | {_n(d.get('rows'))} | {floor} |")
    L.append("")
    for d in pub:
        L.append(f"### `{d['name']}`")
        L.append("")
        L.append(f"- **Source**: {d.get('source', '—')}")
        L.append(f"- **Licence**: {d.get('licence', '—')}"
                 + (f" ([terms]({d['licence_url']}))" if d.get("licence_url") else "")
                 + (f", verified {d['licence_verified']}" if d.get("licence_verified") else ""))
        L.append(f"- **Gold**: {d.get('gold', '—')} — the vendor's own declared keys, "
                 "not ours, so the answer key was written by someone with no stake in "
                 "our score.")
        L.append(f"- **Fetch**: `python fixtures/external/{d.get('fetch', '—')}`")
        if d.get("features"):
            L.append("- **Why it was acquired**: "
                     + ", ".join(f"`{f}`" for f in d["features"][:6]))
        L.append("")

    # --- internal ------------------------------------------------------------
    L.append(f"## Acquired, internal only ({len(internal)})")
    L.append("")
    L.append("Listed because withholding a result silently is indistinguishable from "
             "not having one. These datasets are used in development and **no number "
             "from them is published**, here or anywhere.")
    L.append("")
    for d in internal:
        L.append(f"### `{d['name']}` — results withheld")
        L.append("")
        L.append(f"- **Licence**: {d.get('licence', '—')}"
                 + (f" ([terms]({d['licence_url']}))" if d.get("licence_url") else ""))
        L.append("- **Why withheld**: the licence is share-alike, so a gold layer we "
                 "author for it is plausibly a derivative work. We could not ship that "
                 "gold without putting a share-alike obligation on users of our "
                 "output — and a score nobody can reproduce is not a score we are "
                 "willing to quote.")
        L.append("- **What is public**: this entry and the fetch script. No gold, no "
                 "recorded model responses, no measurements.")
        L.append("")

    L.append("## Reproducing any of this")
    L.append("")
    L.append("```bash")
    L.append("python fixtures/build.py                     # the 9 synthetic warehouses")
    L.append("python fixtures/external/fetch_dbt_synthea.py  # one acquired dataset")
    L.append("ANTHROPIC_API_KEY= pytest -q                 # all floors, no API key, $0")
    L.append("```")
    L.append("")
    L.append("The suite replays recorded model responses from `cassettes/`, so the "
             "accuracy floors above are checked on every pull request without an API "
             "key and without spending anything. See `cassettes/README.md`.")
    L.append("")
    return "\n".join(L)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != text:
            print(f"{OUT.relative_to(OSS)} is out of date: "
                  "re-run `python fixtures/render_warehouses.py`")
            return 1
        print(f"{OUT.relative_to(OSS)} is current")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(OSS)} ({len(text.splitlines())} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
